function cookieLang(): string | undefined {
  return document.cookie.match(/(?:^|; )lang=(en|es)/)?.[1];
}

export const lang: "en" | "es" = (cookieLang() ?? (navigator.language.toLowerCase().startsWith("es") ? "es" : "en")) as "en" | "es";

export function switchLang(): void {
  document.cookie = `lang=${lang === "es" ? "en" : "es"}; path=/; max-age=31536000; samesite=lax; secure`;
  location.reload();
}

